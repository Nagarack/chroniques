'use strict';
const test=require('node:test');const assert=require('node:assert');const L=require('../src/logic.js');
test('inspiration héroïque : accorder, utiliser, donner',()=>{const s=L.initialState();const [a,b]=s.characters;
 assert.throws(()=>L.setInspiration(s,a.owner,a.id,'give'),/MJ/);
 L.setInspiration(s,'mj',a.id,'give');assert.strictEqual(a.inspiration,true);
 assert.throws(()=>L.setInspiration(s,'mj',a.id,'give'),/déjà/);
 L.setInspiration(s,'mj',a.id,'give'.replace('give','remove'));assert.strictEqual(a.inspiration,false);
 L.setInspiration(s,'mj',a.id,'give');
 assert.throws(()=>L.setInspiration(s,b.owner,a.id,'use'),/Accès refusé/);
 L.setInspiration(s,a.owner,a.id,'pass',b.id);assert.strictEqual(a.inspiration,false);assert.strictEqual(b.inspiration,true);
 assert.throws(()=>L.setInspiration(s,b.owner,b.id,'pass',b.id),/introuvable/);
 L.setInspiration(s,b.owner,b.id,'use');assert.strictEqual(b.inspiration,false);
 assert.throws(()=>L.setInspiration(s,b.owner,b.id,'use'),/pas l’inspiration/);
 assert.ok(s.combat.log.some(e=>/donne son inspiration/.test(e.msg)));});
test('inspiration : action serveur et projection joueur',async t=>{const f=await require('./_fixture.js').fixture(t);
 let r=await f.action('inspiration',{id:f.a.id,mode:'give'},f.pa);assert.notStrictEqual(r.status,200);
 r=await f.action('inspiration',{id:f.a.id,mode:'give'});assert.strictEqual(r.status,200);
 const seen=(await f.call('/api/state',{cookie:f.pb})).data.state;assert.strictEqual(seen.characters.find(p=>p.id===f.a.id).inspiration,true);
 r=await f.action('inspiration',{id:f.a.id,mode:'pass',target:f.b.id},f.pa);assert.strictEqual(r.status,200);
 const after=(await f.call('/api/state',{cookie:f.gm})).data.state;assert.strictEqual(after.characters.find(p=>p.id===f.b.id).inspiration,true);
 r=await f.action('inspiration',{id:f.b.id,mode:'zap'},f.pb);assert.strictEqual(r.status,400);});
